import test from 'tape'
import nlp from '../../_lib.js'
const here = '[de-core] '
const txt = 'Der Hund läuft über die Straße. Die Katze schläft.'

test('text output:', function (t) {
  const doc = nlp(txt)
  t.equal(doc.text(), txt, here + 'text is unchanged')
  t.equal(doc.length, 2, here + 'two sentences')
  t.equal(doc.wordCount(), 9, here + 'wordCount')
  t.equal(doc.terms().length, 9, here + 'terms')
  t.equal(doc.eq(1).text(), 'Die Katze schläft.', here + 'eq')
  t.equal(doc.first().text(), 'Der Hund läuft über die Straße.', here + 'first')
  t.equal(doc.last().text(), 'Die Katze schläft.', here + 'last')
  t.equal(doc.slice(1).text(), 'Die Katze schläft.', here + 'slice')
  t.equal(doc.text('normal'), 'der hund läuft über die straße. die katze schläft.', here + 'normal text keeps umlauts')
  t.deepEqual(doc.out('array'), ['Der Hund läuft über die Straße.', 'Die Katze schläft.'], here + 'out array')
  t.equal(doc.terms().eq(2).text(), 'läuft', here + 'terms eq')
  t.equal(doc.firstTerms().out('array').join(' '), 'Der Die', here + 'firstTerms')
  t.equal(doc.lastTerms().out('array').join(' '), 'Straße. schläft.', here + 'lastTerms')
  t.equal(doc.none().found, false, here + 'none')
  t.equal(doc.match('katze').all().text(), txt, here + 'all')
  t.equal(doc.match('katze').fullSentences().text(), 'Die Katze schläft.', here + 'fullSentences')
  t.end()
})

test('json output:', function (t) {
  const json = nlp(txt).json()
  t.equal(json.length, 2, here + 'json sentences')
  t.equal(json[0].text, 'Der Hund läuft über die Straße.', here + 'json text')
  t.equal(json[0].terms.length, 6, here + 'json terms')
  t.equal(json[0].terms[5].text, 'Straße', here + 'json term text')
  t.equal(json[0].terms[5].normal, 'straße', here + 'json normal')
  t.equal(json[0].terms[5].post, '. ', here + 'json post')
  t.ok(Array.isArray(json[0].terms[1].tags), here + 'json tags are an array')
  const off = nlp(txt).json({ offset: true })
  t.equal(off[1].offset.start, 32, here + 'offset start')
  t.equal(txt.substr(off[1].offset.start, off[1].offset.length), 'Die Katze schläft.', here + 'offset length')
  const m = nlp(txt).match('straße').json({ offset: true })[0]
  t.equal(txt.substr(m.offset.start, 6), 'Straße', here + 'offset of a match, after umlauts')
  t.end()
})

test('match in german:', function (t) {
  const doc = nlp(txt)
  t.equal(doc.match('straße').text(), 'Straße', here + 'match is case-insensitive')
  t.equal(doc.match('Straße').text(), 'Straße', here + 'titlecase match')
  t.equal(doc.match('STRASSE').found, false, here + 'ß is not ss')
  t.equal(doc.match('läuft über').text(), 'läuft über', here + 'umlauts match')
  t.equal(doc.match('lauft').found, false, here + 'an umlaut is not its vowel')
  t.equal(nlp('Der HUND schläft').match('hund').found, true, here + 'uppercase text')
  t.equal(doc.has('katze'), true, here + 'has')
  t.equal(doc.has('pferd'), false, here + 'has not')
  t.equal(doc.if('katze').text(), 'Die Katze schläft.', here + 'if')
  t.equal(doc.ifNo('katze').text(), 'Der Hund läuft über die Straße.', here + 'ifNo')
  t.equal(doc.match('hund .').text(), 'Hund läuft', here + 'wildcard')
  t.equal(doc.match('hund * straße').text(), 'Hund läuft über die Straße', here + 'greedy wildcard')
  t.equal(doc.match('(hund|katze)').length, 2, here + 'OR')
  t.equal(doc.match('^die').text(), 'Die', here + 'start anchor')
  t.equal(doc.match('schläft$').text(), 'schläft', here + 'end anchor')
  t.equal(doc.match('der [.] läuft', 0).text(), 'Hund', here + 'capture group')
  t.equal(doc.match('der [<tier>.] läuft').groups('tier').text(), 'Hund', here + 'named group')
  t.equal(doc.match('/^str/').text(), 'Straße', here + 'regex')
  t.equal(doc.match('über die?').text(), 'über die', here + 'optional')
  t.equal(doc.match('!der hund').found, false, here + 'negative')
  t.equal(doc.matchOne('die').text(), 'die', here + 'matchOne')
  t.equal(doc.match('die').length, 2, here + 'two matches')
  t.equal(doc.match('@hasPeriod').length, 2, here + 'method match')
  t.equal(doc.match('@isTitleCase').length, 5, here + 'titlecase method')
  t.end()
})

test('look around:', function (t) {
  const doc = nlp(txt)
  t.equal(doc.match('hund').before().text(), 'Der', here + 'before')
  t.equal(doc.match('hund').after().text(), 'läuft über die Straße', here + 'after')
  t.equal(doc.match('hund').lookAhead('über').text(), 'über', here + 'lookAhead')
  t.equal(doc.match('hund').lookAfter('über').text(), 'über', here + 'lookAfter')
  t.equal(doc.match('läuft').lookBehind('hund').text(), 'Hund', here + 'lookBehind')
  t.equal(doc.match('läuft').lookBefore('hund').text(), 'Hund', here + 'lookBefore')
  t.equal(doc.match('hund').growRight('läuft').text(), 'Hund läuft', here + 'growRight')
  t.equal(doc.match('hund').growLeft('der').text(), 'Der Hund', here + 'growLeft')
  t.equal(doc.match('läuft').grow('(hund|über)').text(), 'Hund läuft über', here + 'grow')
  t.deepEqual(doc.eq(0).splitOn('über').out('array'), ['Der Hund läuft', 'über', 'die Straße.'], here + 'splitOn')
  t.deepEqual(doc.eq(0).splitBefore('über').out('array'), ['Der Hund läuft', 'über die Straße.'], here + 'splitBefore')
  t.deepEqual(doc.eq(0).splitAfter('über').out('array'), ['Der Hund läuft über', 'die Straße.'], here + 'splitAfter')
  t.deepEqual(doc.eq(0).split('über').out('array'), ['Der Hund läuft über', 'die Straße.'], here + 'split')
  t.end()
})

test('pointers:', function (t) {
  const doc = nlp(txt)
  const a = doc.match('hund läuft')
  const b = doc.match('läuft über')
  t.equal(a.union(b).text(), 'Hund läuft über', here + 'union')
  t.equal(a.and(b).text(), 'Hund läuft über', here + 'and')
  t.equal(a.intersection(b).text(), 'läuft', here + 'intersection')
  t.equal(a.not('läuft').text(), 'Hund', here + 'not')
  t.equal(a.difference('läuft').text(), 'Hund', here + 'difference')
  t.equal(doc.eq(1).complement().text(), 'Der Hund läuft über die Straße.', here + 'complement')
  t.equal(doc.match('die').unique().length, 1, here + 'unique')
  t.deepEqual(nlp(txt).reverse().out('array'), ['Die Katze schläft.', 'Der Hund läuft über die Straße.'], here + 'reverse')
  t.deepEqual(nlp('zebra. apfel. banane.').sort('alpha').out('array'), ['apfel.', 'banane.', 'zebra.'], here + 'sort alpha')
  t.equal(nlp('Die Katze schläft. Der Hund läuft über die Straße.').sort('length').out('array')[0], 'Der Hund läuft über die Straße.', here + 'sort length')
  t.end()
})

