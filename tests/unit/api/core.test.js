test('insert and replace:', function (t) {
  const str = 'der Hund schläft'
  t.equal(nlp(str).match('hund').insertBefore('kleine').all().text(), 'der kleine Hund schläft', here + 'insertBefore')
  t.equal(nlp(str).match('hund').prepend('kleine').all().text(), 'der kleine Hund schläft', here + 'prepend')
  t.equal(nlp(str).match('hund').insertAfter('dort').all().text(), 'der Hund dort schläft', here + 'insertAfter')
  t.equal(nlp(str).match('hund').append('dort').all().text(), 'der Hund dort schläft', here + 'append')
  t.equal(nlp(str).match('hund').insert('dort').all().text(), 'der Hund dort schläft', here + 'insert')
  t.equal(nlp(str).replace('hund', 'Bär').all().text(), 'der Bär schläft', here + 'replace')
  t.equal(nlp(str).replace('hund', 'große Bär').all().text(), 'der große Bär schläft', here + 'replace with two words')
  t.equal(nlp(str).match('hund').replaceWith('Vogel').all().text(), 'der Vogel schläft', here + 'replaceWith')
  t.equal(nlp('der Hund schläft. der Hund bellt.').replace('hund', 'Bär').all().text(), 'der Bär schläft. der Bär bellt.', here + 'replace every match')
  t.equal(nlp('der kleine Hund schläft').remove('kleine').text(), 'der Hund schläft', here + 'remove')
  t.equal(nlp('der kleine Hund schläft').delete('kleine').text(), 'der Hund schläft', here + 'delete')
  t.equal(nlp('der kleine Hund schläft').match('kleine').remove().all().text(), 'der Hund schläft', here + 'remove self')
  t.equal(nlp('Der Hund schläft.').concat('Die Katze auch.').length, 2, here + 'concat')
  // the original doc is changed too
  const doc = nlp(str)
  doc.match('hund').replaceWith('Vogel')
  t.equal(doc.text(), 'der Vogel schläft', here + 'replaceWith mutates')
  // new words are parsed, too
  t.deepEqual(nlp('ich habe Hunde').match('hunde').insertBefore('drei').all().numbers().get(), [3], here + 'an inserted number')
  t.deepEqual(nlp('ich habe drei Hunde').replace('drei', 'siebzehn').all().numbers().get(), [17], here + 'a replaced number')
  t.end()
})

test('whitespace and punctuation:', function (t) {
  const str = 'der Hund schläft'
  t.equal(nlp('  der Hund  ').trim().text(), 'der Hund', here + 'trim')
  t.equal(nlp(str).hyphenate().text(), 'der-Hund-schläft', here + 'hyphenate')
  t.equal(nlp('der-Hund-schläft').dehyphenate().text(), str, here + 'dehyphenate')
  t.equal(nlp('der-Hund-schläft').deHyphenate().text(), str, here + 'deHyphenate')
  t.equal(nlp(str).match('hund').toQuotations().all().text(), 'der "Hund" schläft', here + 'toQuotations')
  t.equal(nlp(str).match('hund').toQuotations('„', '“').all().text(), 'der „Hund“ schläft', here + 'german quotes')
  t.equal(nlp(str).match('hund').toQuotation('»', '«').all().text(), 'der »Hund« schläft', here + 'toQuotation')
  t.equal(nlp(str).match('hund').toParentheses().all().text(), 'der (Hund) schläft', here + 'toParentheses')
  t.equal(nlp(str).match('hund').pre('~').all().text(), 'der ~Hund schläft', here + 'pre')
  t.equal(nlp(str).match('schläft').post('!').all().text(), 'der Hund schläft!', here + 'post')
  t.equal(nlp('„Wir bleiben hier.“').terms().length, 3, here + 'quotes are not terms')
  t.equal(nlp('„Wir bleiben hier.“').match('^wir bleiben hier$').found, true, here + 'german quotes are punctuation')
  t.equal(nlp('„Wir bleiben hier.“').text(), '„Wir bleiben hier.“', here + 'quotes survive')
  t.equal(nlp('»Wir bleiben hier.«').match('^wir').found, true, here + 'guillemets')
  t.equal(nlp('Wir (also ich) bleiben').match('ich').text(), 'ich', here + 'parentheses are punctuation')
  t.end()
})

test('tags:', function (t) {
  const doc = nlp('der Hund schläft')
  doc.match('hund').tag('Vierbeiner')
  t.equal(doc.match('#Vierbeiner').text(), 'Hund', here + 'a new tag')
  doc.match('hund').unTag('Vierbeiner')
  t.equal(doc.has('#Vierbeiner'), false, here + 'unTag')
  doc.match('hund').tag('#Person')
  t.equal(doc.has('#Person'), true, here + 'tag with a hash')
  t.equal(doc.match('hund').has('#Noun'), true, here + 'a Person is a Noun')
  doc.match('hund').tag('Verb')
  t.equal(doc.match('hund').has('#Noun'), false, here + 'Verb removes Noun')
  const d = nlp('der Hund schläft')
  d.match('hund').tag('Noun').tagSafe('Verb')
  t.equal(d.match('hund').has('#Verb'), false, here + 'tagSafe does not over-write')
  t.equal(d.match('hund').has('#Noun'), true, here + 'tagSafe keeps the noun')
  t.equal(nlp('drei Hunde').match('drei').canBe('Noun').found, false, here + 'a value cannot be a noun')
  t.equal(nlp('drei Hunde').match('drei').canBe('Cardinal').found, true, here + 'a value can be a cardinal')
  t.end()
})

test('loops:', function (t) {
  const doc = nlp(txt)
  const arr = []
  doc.forEach(s => arr.push(s.wordCount()))
  t.deepEqual(arr, [6, 3], here + 'forEach')
  t.deepEqual(doc.map(s => ({ words: s.wordCount() }), []), [{ words: 6 }, { words: 3 }], here + 'map to an array')
  t.equal(doc.map(s => s.terms().first()).out('array').join(' '), 'Der Die', here + 'map to a view')
  t.equal(doc.filter(s => s.has('katze')).text(), 'Die Katze schläft.', here + 'filter')
  t.equal(doc.find(s => s.has('katze')).text(), 'Die Katze schläft.', here + 'find')
  t.equal(doc.some(s => s.has('katze')), true, here + 'some')
  t.equal(doc.some(s => s.has('pferd')), false, here + 'some - none')
  t.equal(doc.random(1).length, 1, here + 'random')
  t.equal(doc.terms().random(3).length, 3, here + 'random 3')
  t.end()
})

test('clone:', function (t) {
  const doc = nlp('der Hund schläft')
  const copy = doc.clone()
  copy.replace('hund', 'Bär')
  copy.match('schläft').tag('Foo')
  t.equal(doc.text(), 'der Hund schläft', here + 'original text is untouched')
  t.equal(copy.text(), 'der Bär schläft', here + 'clone is changed')
  t.equal(doc.has('#Foo'), false, here + 'original tags are untouched')
  const nums = nlp('ich habe 1.234 Euro')
  const c = nums.clone()
  c.numbers().add(1)
  t.equal(nums.text(), 'ich habe 1.234 Euro', here + 'numbers - original')
  t.equal(c.text(), 'ich habe 1.235 Euro', here + 'numbers - clone')
  t.end()
})

